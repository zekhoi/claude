import { z } from "zod";

export const REGISTRY_SCHEMA_VERSION = 1;
export const MANIFEST_SCHEMA_VERSION = 1;
export const OUTPUT_SCHEMA_VERSION = 1;

export const ITEM_TYPES = ["guideline", "rule", "skill", "agent"] as const;
export type ItemType = (typeof ITEM_TYPES)[number];

const slug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const semver = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const sha256 = /^[0-9a-f]{64}$/;

export const ItemIdSchema = z
  .string()
  .regex(new RegExp(`^(?:${ITEM_TYPES.join("|")})/${slug.source.slice(1, -1)}$`), {
    message: "must be <type>/<kebab-case-name>",
  });

export const PresetIdSchema = z.string().regex(new RegExp(`^preset/${slug.source.slice(1, -1)}$`), {
  message: "must be preset/<kebab-case-name>",
});

/** How a file reaches the target: copied whole, or written into a delimited block of a shared file. */
export const InstallModeSchema = z.enum(["file", "managed-block"]);
export type InstallMode = z.infer<typeof InstallModeSchema>;

export const SourceFileSchema = z.strictObject({
  source: z.string().min(1),
  destination: z.string().min(1),
  install: InstallModeSchema.default("file"),
});

export const RegistryItemSchema = z.strictObject({
  schemaVersion: z.literal(REGISTRY_SCHEMA_VERSION),
  id: ItemIdSchema,
  version: z.string().regex(semver, { message: "must be MAJOR.MINOR.PATCH" }),
  type: z.enum(ITEM_TYPES),
  description: z.string().min(1).max(300),
  // Reserved; the initial release requires an empty list (validated separately for a clear diagnostic).
  dependencies: z.array(ItemIdSchema).default([]),
  files: z.array(SourceFileSchema).min(1),
});
export type RegistryItem = z.infer<typeof RegistryItemSchema>;

export const PresetSchema = z.strictObject({
  schemaVersion: z.literal(REGISTRY_SCHEMA_VERSION),
  id: PresetIdSchema,
  description: z.string().min(1).max(300),
  items: z.array(ItemIdSchema).min(1),
});
export type Preset = z.infer<typeof PresetSchema>;

/** `registry/index.json` in source form. Checksums are never stored here. */
export const SourceIndexSchema = z.strictObject({
  schemaVersion: z.literal(REGISTRY_SCHEMA_VERSION),
  items: z.array(RegistryItemSchema),
});

export const PackagedFileSchema = SourceFileSchema.extend({
  install: InstallModeSchema,
  sha256: z.string().regex(sha256),
});

export const PackagedItemSchema = RegistryItemSchema.extend({
  files: z.array(PackagedFileSchema).min(1),
});
export type PackagedItem = z.infer<typeof PackagedItemSchema>;

/** The index generated by the build and bundled in the npm package. */
export const PackagedIndexSchema = z.strictObject({
  schemaVersion: z.literal(REGISTRY_SCHEMA_VERSION),
  items: z.array(PackagedItemSchema),
  presets: z.array(PresetSchema),
});
export type PackagedIndex = z.infer<typeof PackagedIndexSchema>;

const ManifestFileSchema = z.strictObject({
  destination: z.string().min(1),
  install: InstallModeSchema,
  /** Normalized checksum of the content last installed (block body for managed blocks). */
  sha256: z.string().regex(sha256),
});

/** `.agent-kit/manifest.json` in a target project. CLI-owned bookkeeping. */
export const ManifestSchema = z.strictObject({
  manifestSchemaVersion: z.literal(MANIFEST_SCHEMA_VERSION),
  cliVersion: z.string().min(1),
  adapter: z.literal("claude"),
  /** Presets the user requested; informational only, never used to add items during update. */
  presets: z.array(PresetIdSchema),
  items: z.record(
    ItemIdSchema,
    z.strictObject({
      version: z.string().regex(semver),
      files: z.array(ManifestFileSchema).min(1),
    }),
  ),
  /** Root instruction files the CLI created, eligible for deletion on uninstall when left empty. */
  createdFiles: z.array(z.string()),
  /** Whether the CLAUDE.md import of AGENTS.md is in a CLI-managed block or was already user-owned. */
  claudeImport: z.enum(["managed", "user-owned"]),
  /** Project context file referenced from the managed guidelines block; always project-owned. */
  contextPath: z.string().optional(),
});
export type Manifest = z.infer<typeof ManifestSchema>;

export const ChangeActionSchema = z.enum([
  "create",
  "update",
  "unchanged",
  "adopt",
  "delete",
  "conflict",
]);

/** One planned operation produced by the core and applied by the writer. */
export const PlannedChangeSchema = z.strictObject({
  action: ChangeActionSchema,
  itemId: ItemIdSchema.optional(),
  destination: z.string(),
  install: InstallModeSchema,
  fromVersion: z.string().optional(),
  toVersion: z.string().optional(),
  reason: z.string().optional(),
});
export type PlannedChange = z.infer<typeof PlannedChangeSchema>;

export const InstallPlanSchema = z.strictObject({
  target: z.string(),
  changes: z.array(PlannedChangeSchema),
});
export type InstallPlan = z.infer<typeof InstallPlanSchema>;
